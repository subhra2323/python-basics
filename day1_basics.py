# Day 1: Python Basics

# Variables
name = "Rupam"
age = 23

print(name)
print(age)

# Data Types
a = 10
b = 10.5
c = "Python"
d = True

print(type(a))
print(type(b))
print(type(c))
print(type(d))

# String Indexing
language = "Python"

print(language[0])
print(language[-1])

# String Slicing
print(language[0:3])

# Type Conversion
number = 12
text = str(number)

print(type(text))
